"""Integration test for sdcard/mpc-mod/apply.sh - the on-device applier.

Runs the real apply.sh under the host shell against a SYNTHETIC stock binary,
with PATH shims standing in for the device-only commands (sha256sum, mount,
systemctl, pkill). No hardware, no vendor binary, no root.

The thing under test is the phase-2 behaviour (clone + bind-mount only) AND the
crash-guard ordering fix: .pending must be cleared BEFORE the service restart, so
a restart that kills the script can never make the next run read a success as a
failure.

Run: python3 -m pytest tests/ -q
"""
import hashlib
import os
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
APPLY_SH = REPO / "sdcard" / "mpc-mod" / "apply.sh"


def _write_exec(path: Path, content: str):
    path.write_text(content)
    path.chmod(0o755)


def _shim_bin(tmp_path: Path, events: Path, pending: Path) -> Path:
    """A PATH dir whose shims record what apply.sh invokes."""
    binsh = tmp_path / "bin"
    binsh.mkdir()
    # macOS has `shasum`, not `sha256sum`; Linux CI has both. Prefer the real one.
    real_sha = shutil.which("sha256sum")
    if real_sha:
        _write_exec(binsh / "sha256sum", f'#!/bin/sh\nexec {real_sha} "$@"\n')
    else:
        _write_exec(binsh / "sha256sum", '#!/bin/sh\nexec shasum -a 256 "$@"\n')
    _write_exec(binsh / "mount", textwrap.dedent(f"""\
        #!/bin/sh
        echo "mount $*" >> "{events}"
        exit 0
    """))
    # Record, at restart time, whether the crash-guard marker still exists.
    _write_exec(binsh / "systemctl", textwrap.dedent(f"""\
        #!/bin/sh
        echo "systemctl $*" >> "{events}"
        if [ -f "{pending}" ]; then echo "PENDING_AT_RESTART" >> "{events}"; fi
        exit 0
    """))
    _write_exec(binsh / "pkill", '#!/bin/sh\nexit 0\n')
    return binsh


def _run_apply(tmp_path: Path):
    stock = tmp_path / "stock.bin"
    stock.write_bytes(b"MPC-SAMPLE-STOCK\n" + bytes(range(256)) * 8)
    stock_sha = hashlib.sha256(stock.read_bytes()).hexdigest()

    sd = tmp_path / "sd" / "mpc-mod"
    sd.mkdir(parents=True)
    shutil.copy(APPLY_SH, sd / "apply.sh")
    (sd / "apply.sh").chmod(0o755)

    # Zero-patch (clone) list: headers only. target == result == stock sha.
    (sd / "patches.list").write_text(
        "# generated by test\n"
        f"#target-size {stock.stat().st_size}\n"
        f"#target-sha256 {stock_sha}\n"
        f"#result-sha256 {stock_sha}\n"
    )

    events = tmp_path / "events.log"
    work = tmp_path / "work"
    binsh = _shim_bin(tmp_path, events, sd / ".pending")

    env = dict(os.environ)
    env["PATH"] = f"{binsh}{os.pathsep}" + env.get("PATH", "")
    env["MPC_STOCK"] = str(stock)
    env["MPC_WORK"] = str(work)

    proc = subprocess.run(
        ["sh", str(sd / "apply.sh")],
        env=env, capture_output=True, text=True,
    )
    return proc, sd, work, stock, events


def test_apply_sh_clones_binds_and_restarts(tmp_path):
    proc, sd, work, stock, events = _run_apply(tmp_path)
    assert proc.returncode == 0, f"stdout={proc.stdout!r} stderr={proc.stderr!r}"
    log = events.read_text()

    # Bind-mounted the RAM copy over the (fake) stock path, then restarted ac50.
    assert "mount --bind" in log
    assert str(stock) in log
    assert "systemctl restart ac50.service" in log

    # The RAM copy is a byte-identical clone of stock (zero patches).
    out = work / "MPC-Sample-patched"
    assert out.read_bytes() == stock.read_bytes()


def test_apply_sh_clears_pending_before_restart(tmp_path):
    # The ordering fix: by the time the service restart runs, .pending is gone.
    proc, sd, work, stock, events = _run_apply(tmp_path)
    assert proc.returncode == 0, f"stdout={proc.stdout!r} stderr={proc.stderr!r}"
    log = events.read_text()
    assert "PENDING_AT_RESTART" not in log, (
        ".pending still present when ac50 was restarted - a restart that kills "
        "apply.sh would strand it and the crash guard would count this success "
        "as a failure"
    )
    # And on clean success the marker is cleared.
    assert not (sd / ".pending").exists()


def test_apply_sh_crash_guard_refuses_after_max_fails(tmp_path):
    # A stuck .pending at/above MAX_FAILS makes apply.sh refuse and leave stock.
    proc, sd, work, stock, events = _run_apply(tmp_path)
    assert proc.returncode == 0
    # Simulate two prior crashed attempts, then run again.
    (sd / ".pending").write_text("2\n")
    env = dict(os.environ)
    binsh = sd.parent.parent / "bin"
    env["PATH"] = f"{binsh}{os.pathsep}" + env.get("PATH", "")
    env["MPC_STOCK"] = str(stock)
    env["MPC_WORK"] = str(tmp_path / "work2")
    proc2 = subprocess.run(
        ["sh", str(sd / "apply.sh")],
        env=env, capture_output=True, text=True,
    )
    assert proc2.returncode != 0
    assert "staying on stock" in (proc2.stdout + proc2.stderr)


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-q"]))
