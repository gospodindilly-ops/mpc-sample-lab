#!/usr/bin/env python3
"""Convert fixed-width BDF fonts (ASCII 32..126) into a C header of 1-bit glyph rows.

Usage: bdf2c.py out.h NAME=font.bdf [NAME=font.bdf ...]
Each font becomes `static const unsigned char NAME[95][H]` (one byte per row, MSB = leftmost pixel)
plus NAME_W / NAME_H defines. Glyphs wider than 8 pixels are rejected.
"""
import sys


def glyphs(path):
    w = h = None
    out, enc, rows, in_bitmap = {}, None, [], False
    for line in open(path, encoding='latin-1'):
        parts = line.split()
        if not parts:
            continue
        if parts[0] == 'FONTBOUNDINGBOX':
            w, h = int(parts[1]), int(parts[2])
        elif parts[0] == 'ENCODING':
            enc = int(parts[1])
        elif parts[0] == 'BITMAP':
            in_bitmap, rows = True, []
        elif parts[0] == 'ENDCHAR':
            if enc is not None and 32 <= enc <= 126:
                assert len(rows) == h, f'{path}: glyph {enc} has {len(rows)} rows, expected {h}'
                out[enc] = rows
            in_bitmap, enc = False, None
        elif in_bitmap:
            rows.append(int(parts[0], 16) >> (len(parts[0]) * 4 - 8))  # keep the leftmost 8 pixels
    assert w and w <= 8, f'{path}: width {w} not supported'
    missing = [c for c in range(32, 127) if c not in out]
    assert not missing, f'{path}: missing glyphs {missing}'
    return w, h, [out[c] for c in range(32, 127)]


def main():
    lines = ['// Generated by tools/bdf2c.py from Terminus (SIL Open Font License 1.1, see assets/fonts/).',
             '// Glyphs for ASCII 32..126, one byte per row, MSB = leftmost pixel.', '#pragma once', '']
    for spec in sys.argv[2:]:
        name, path = spec.split('=', 1)
        w, h, gl = glyphs(path)
        lines += [f'#define {name}_W {w}', f'#define {name}_H {h}', f'static const unsigned char {name}[95][{h}] = {{']
        lines += ['    {' + ', '.join(f'0x{r:02x}' for r in g) + '},' for g in gl]
        lines += ['};', '']
    open(sys.argv[1], 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
